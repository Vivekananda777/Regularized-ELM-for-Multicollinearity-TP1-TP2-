def _build_styles():
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle('MLTitle', parent=styles['Title'],
                                  fontSize=22, textColor=colors.HexColor('#1a1a2e'),
                                  spaceAfter=6, alignment=TA_CENTER)
    subtitle_style = ParagraphStyle('MLSub', parent=styles['Normal'],
                                     fontSize=11, textColor=colors.HexColor('#6c757d'),
                                     spaceAfter=20, alignment=TA_CENTER)
    h2_style = ParagraphStyle('MLH2', parent=styles['Heading2'],
                               fontSize=14, textColor=colors.HexColor('#16213e'),
                               spaceBefore=18, spaceAfter=8)
    body_style = ParagraphStyle('MLBody', parent=styles['Normal'],
                                 fontSize=10, textColor=colors.HexColor('#343a40'),
                                 spaceAfter=6)
    return title_style, subtitle_style, h2_style, body_style


@login_required
def export_results_pdf(request):
    results = TrainingResult.objects.filter(
        status='completed'
    ).select_related('dataset', 'algorithm_config', 'user').order_by('-created_at')

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4,
                            topMargin=0.75*inch, bottomMargin=0.75*inch,
                            leftMargin=0.75*inch, rightMargin=0.75*inch)
    title_style, subtitle_style, h2_style, body_style = _build_styles()
    elements = []

    # Cover
    elements.append(Spacer(1, 0.5*inch))
    elements.append(Paragraph("ML Benchmark Platform", title_style))
    elements.append(Paragraph("Comprehensive Performance Report", subtitle_style))
    elements.append(Paragraph(
        f"Generated: {timezone.now().strftime('%B %d, %Y at %H:%M UTC')} | "
        f"By: {request.user.get_full_name() or request.user.username}",
        subtitle_style))
    elements.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor('#4f46e5')))
    elements.append(Spacer(1, 20))

    # Summary stats
    elements.append(Paragraph("Executive Summary", h2_style))
    summary_data = [
        ['Metric', 'Value'],
        ['Total Experiments', str(results.count())],
        ['Active Datasets', str(Dataset.objects.filter(status='active').count())],
        ['Report Date', timezone.now().strftime('%B %d, %Y')],
        ['Generated By', request.user.get_full_name() or request.user.username],
    ]
    summary_table = Table(summary_data, colWidths=[3*inch, 3.5*inch])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#4f46e5')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTSIZE', (0, 0), (-1, -1), 10),
        ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.HexColor('#f8f9fa'), colors.white]),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#dee2e6')),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('ROWHEIGHT', (0, 0), (-1, -1), 20),
    ]))
    elements.append(summary_table)
    elements.append(Spacer(1, 20))

