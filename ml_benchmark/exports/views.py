    if len(cv_data) > 1:
        cv_table = Table(cv_data, repeatRows=1,
                         colWidths=[1.5*inch, 1.5*inch, 0.7*inch, 0.7*inch,
                                    0.7*inch, 0.7*inch, 0.7*inch, 0.7*inch])
